// Build helper (no dependencies): regenerates lib/samples.js and docs/RULES.md, and writes standalone.html
// (a single file that works from file:// because it needs no module loading). Run: node scripts/build.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { CATALOG, CATEGORIES, OWASP, ATLAS } from '../lib/meta.js'

const root = new URL('../', import.meta.url)
const rd = (p) => readFileSync(new URL(p, root), 'utf8')

export function samplesSource() {
  const files = readdirSync(new URL('samples/', root)).filter((f) => /\.(json|ya?ml)$/.test(f)).sort()
  const items = files.map((f) => ({ file: f, text: rd('samples/' + f) }))
  return `// GENERATED by scripts/build.mjs from samples/*. Do not edit by hand.\nexport const SAMPLES = ${JSON.stringify(items, null, 1)}\n`
}

export function rulesMarkdown() {
  const L = ['# Rule reference', '', 'Generated from `lib/meta.js` by `node scripts/build.mjs`. Severity shown is the typical level; some rules raise or lower it with context.', '',
    '| ID | Category | Typical severity | OWASP LLM Top 10 | MITRE ATLAS | Fix effort |', '|---|---|---|---|---|---|']
  for (const [id, c] of Object.entries(CATALOG)) L.push(`| [${id}](#${id.toLowerCase()}) | ${CATEGORIES[c.cat]} | ${c.sev} | ${(c.owasp || []).join(', ') || '-'} | ${(c.atlas || []).join(', ') || '-'} | ${['', 'prompt line', 'config or tool change', 'architecture'][c.effort]} |`)
  L.push('')
  for (const [id, c] of Object.entries(CATALOG)) {
    L.push(`## ${id}`, '', `**${c.title}** (${CATEGORIES[c.cat]}, typical severity ${c.sev})`, '', c.why, '',
      `OWASP: ${(c.owasp || []).map((o) => `${o} ${OWASP[o]}`).join('; ') || '-'}  `, `ATLAS: ${(c.atlas || []).map((a) => `${a} ${ATLAS[a]}`).join('; ') || '-'}`, '',
      '**Weak:**', '', '```', c.bad, '```', '', '**Better:**', '', '```', c.good, '```', '', `**Fix:** ${c.fix}`, '')
  }
  return L.join('\n')
}

const ORDER = ['lib/meta.js', 'lib/parse.js', 'engine.js', 'lib/charts.js', 'lib/report.js', 'lib/advice.js', 'lib/store.js', 'lib/samples.js', 'app.js']

export function standaloneHtml() {
  const names = new Map()
  const parts = []
  for (const f of ORDER) {
    let src = rd(f)
    src = src.replace(/^import\s[^\n]*from\s+['"][^'"]+['"]\s*;?\s*$/gm, '')
    src = src.replace(/^export\s*\{[^}]*\}\s*(from\s+['"][^'"]+['"])?\s*;?\s*$/gm, '')
    src = src.replace(/^export\s+(?=(async\s+)?(function|const|let|class)\b)/gm, '')
    if (/^\s*(import|export)\b/m.test(src.replace(/\/\/.*$/gm, ''))) throw new Error('unsupported import/export syntax in ' + f)
    for (const m of src.matchAll(/^(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) {
      if (names.has(m[1])) throw new Error(`duplicate top-level name "${m[1]}" in ${f} and ${names.get(m[1])}`)
      names.set(m[1], f)
    }
    parts.push(`// ---- ${f}\n${src}`)
  }
  const script = `'use strict';\n(() => {\n${parts.join('\n')}\n})()\n`
  const css = rd('app.css')
  const hash = createHash('sha256').update(script).digest('base64')
  let html = rd('index.html')
  html = html.replace(/script-src 'self'/, `script-src 'sha256-${hash}'`)
  html = html.replace('<link rel="stylesheet" href="app.css">', () => `<style>\n${css}\n</style>`)
  html = html.replace('<script type="module" src="app.js"></script>', () => `<script>${script.replace(/<\/script/gi, '<\\/script')}</script>`)
  if (script.includes('</script')) throw new Error('script contains a closing script tag')
  return html
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
  writeFileSync(new URL('lib/samples.js', root), samplesSource())
  mkdirSync(new URL('docs/', root), { recursive: true })
  writeFileSync(new URL('docs/RULES.md', root), rulesMarkdown())
  if (process.argv.includes('--no-standalone')) console.log('samples.js and docs/RULES.md written')
  else { writeFileSync(new URL('standalone.html', root), standaloneHtml()); console.log('samples.js, docs/RULES.md and standalone.html written') }
}
